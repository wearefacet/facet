/**
 * Pure builders for the dev stack files `setup-dev` writes. No filesystem and
 * no network — every function turns its inputs into a file body, so the tests
 * assert the exact output without touching Docker.
 */

/** The values one dev stack is built from. */
export interface DevStackInput {
	/** Hostname the edge serves (default `facet.localhost`). */
	hostname: string;
	/** HTTPS port the edge binds (default `3443`). */
	port: number;
	/** Image tag for both GHCR images (default `latest`). */
	version: string;
	/** Generated secrets — passed in so the caller owns randomness. */
	postgresPassword: string;
	jwtSigningKey: string;
	/** When set, the backend watches this container path for domain bundles. */
	watchPath?: string;
}

/** The main URL browsers reach, without a trailing slash. */
export function instanceUrl(input: Pick<DevStackInput, 'hostname' | 'port'>): string {
	return `https://${input.hostname}:${input.port}`;
}

/** The compose file: the GHCR stack in dev mode, with the dev config mounted. */
export function renderCompose(input: DevStackInput): string {
	const watchMount = input.watchPath === undefined ? '' : '      - ./domains:/watch:ro\n';
	return `# Facet dev stack — generated by "facet-cli setup-dev".
# Image-only (no build) and dev-shaped: APP_ENV=dev, a mounted dev config,
# the known dev credential, and stdout email. Not for production.
#
#   docker compose up -d
#   docker compose run --rm backend db_reset --yes seed:dev   # known admin

name: facet-dev

services:
  postgres:
    image: pgvector/pgvector:0.8.0-pg17
    restart: unless-stopped
    environment:
      POSTGRES_DB: facet
      POSTGRES_USER: facet
      POSTGRES_PASSWORD: \${POSTGRES_PASSWORD:?POSTGRES_PASSWORD is required}
    volumes:
      - pg-data:/var/lib/postgresql/data
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U facet -d facet"]
      interval: 5s
      timeout: 5s
      retries: 12
      start_period: 10s

  redis:
    image: redis:7
    restart: unless-stopped
    command: ["redis-server", "--appendonly", "yes"]
    volumes:
      - redis-data:/data
    healthcheck:
      test: ["CMD", "redis-cli", "ping"]
      interval: 5s
      timeout: 3s
      retries: 12

  backend:
    image: ghcr.io/wearefacet/facet:\${FACET_VERSION:-latest}
    restart: unless-stopped
    environment:
      APP_ENV: dev
      FACET_CONFIG_FILE: /app/config.dev.yml
      DATABASE_URL: postgres://facet:\${POSTGRES_PASSWORD:?POSTGRES_PASSWORD is required}@postgres:5432/facet
      JWT_SIGNING_KEY: \${JWT_SIGNING_KEY:?JWT_SIGNING_KEY is required}
    volumes:
      - ./config.dev.yml:/app/config.dev.yml:ro
      - artifact-store:/data/store
${watchMount}    depends_on:
      postgres:
        condition: service_healthy
      redis:
        condition: service_healthy

  frontend:
    image: ghcr.io/wearefacet/facet-frontend:\${FACET_VERSION:-latest}
    restart: unless-stopped
    environment:
      BACKEND_URL: http://backend:3000
    depends_on:
      backend:
        condition: service_healthy

  caddy:
    image: caddy:2
    restart: unless-stopped
    ports:
      - "\${HTTPS_PORT:-3443}:\${HTTPS_PORT:-3443}"
    environment:
      FACET_HOSTNAME: \${FACET_HOSTNAME:-facet.localhost}
      HTTPS_PORT: \${HTTPS_PORT:-3443}
      BACKEND_URL: http://backend:3000
      FRONTEND_URL: http://frontend:3000
    volumes:
      - caddy-data:/data
      - ./Caddyfile.prod:/etc/caddy/Caddyfile:ro
    depends_on:
      backend:
        condition: service_healthy
      frontend:
        condition: service_healthy

volumes:
  pg-data:
  redis-data:
  caddy-data:
  artifact-store:
`;
}

/** The `.env` the compose reads. Secrets come from the caller. */
export function renderEnv(input: DevStackInput): string {
	return `# Facet dev stack — generated by "facet-cli setup-dev". Git-ignored.
FACET_VERSION=${input.version}
FACET_HOSTNAME=${input.hostname}
HTTPS_PORT=${input.port}

POSTGRES_PASSWORD=${input.postgresPassword}

# ES256 access-token signing key, P-256 in PEM form. Keep it stable.
JWT_SIGNING_KEY="${input.jwtSigningKey.replace(/\n/g, '\\n')}"
`;
}

/**
 * The dev config the backend mounts. It carries only the sections the loader
 * requires plus the dev-only values (stdout mail, non-secure cookies), with
 * container-network addresses. Everything else keeps its loader default.
 */
export function renderDevConfig(input: DevStackInput): string {
	const url = instanceUrl(input);
	const watch =
		input.watchPath === undefined
			? ''
			: `
# Folder-authored doctypes: the backend polls this path and applies every
# bundle it finds. The bind mount is ./domains on the host.
dev:
  domain_watch:
    path: ${input.watchPath}
    poll_ms: 500
    documents: preserve
`;
	return `# Facet dev config — generated by "facet-cli setup-dev".
# Mounted at /app/config.dev.yml; the backend boots with APP_ENV=dev.
# Only the loader-required sections plus the dev-only values. Database
# credentials ride in DATABASE_URL, not here.

host: "${url}"
base_url: "${url}"
artifact_base_url: "${url}"
artifact_grant_secret: "${input.postgresPassword}"

artifact:
  storage:
    type: filesystem
    directory: /data/store

event:
  url: "redis://redis:6379/0"

iam:
  # Plain-HTTP internal hop behind the TLS edge — cookies must not be secure.
  secure_cookies: false

mail:
  # "dev" prints email to stdout: reset and invite links need no relay.
  adapter: dev
  from_address: "no-reply@facet.local"
  from_name: "Facet"

secrets:
  master_key: "${input.postgresPassword}"
${watch}`;
}

/** The edge config. Identical to the release stack's Caddyfile. */
export function renderCaddyfile(): string {
	return `# Facet edge — generated by "facet-cli setup-dev".
# Serves the main host and app hosts behind one TLS port. The frontend and
# backend speak plain HTTP inside the compose network.
{
	auto_https disable_redirects
}

https://{\$FACET_HOSTNAME:localhost}:{\$HTTPS_PORT:3443} {
	tls internal

	@backend path /Api/* /OAuth/* /A/* /Ws/* /Healthcheck /auth/* /.well-known/*
	handle @backend {
		reverse_proxy {\$BACKEND_URL:http://backend:3000}
	}

	handle {
		reverse_proxy {\$FRONTEND_URL:http://frontend:3000}
	}
}
`;
}

/** `facet.config.json` — targets only; no deploy app (out of scope here). */
export function renderFacetConfig(input: DevStackInput): string {
	const config = {
		targets: { dev: { url: instanceUrl(input) } },
		defaultTarget: 'dev'
	};
	return `${JSON.stringify(config, null, '\t')}\n`;
}

/** The `.gitignore` written when the folder is not yet a repo. */
export function renderGitignore(): string {
	return `# Facet dev stack — generated by "facet-cli setup-dev".
.env
.facet.local.json
domains/
node_modules/
dist/
.DS_Store
`;
}
